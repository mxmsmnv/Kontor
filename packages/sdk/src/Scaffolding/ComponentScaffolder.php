    private function readmeFile(): string
    {
        return <<<MD
        # {$this->title}

        `kontor/{$this->packageSlug}` — {$this->description}

        Generated by `Kontor\\SDK\\Scaffolding\\ComponentScaffolder`
        (kontor.md Substage 7.4). Replace this file with a real description
        once the component has actual contents.

        ## Testing

        ```bash
        composer install
        vendor/bin/phpunit
        ```

        MD;
    }

    private function changelogFile(): string
    {
        return <<<MD
        # Changelog

        All notable changes to `kontor/{$this->packageSlug}` are documented here.
        The format follows [Keep a Changelog](https://keepachangelog.com/).

        ## [Unreleased]

        ### Added

        - Scaffolded package skeleton.

        MD;
    }
}
